/// Longest name a peer may give itself in a signal (a profile name is at
/// most 60 characters).
const int kMaxSignalSenderNameChars = 64;

/// Longest note attached to a friend request.
const int kMaxFriendRequestMessageChars = 1000;

/// Longest group name and description taken from an invitation.
const int kMaxSignalGroupNameChars = 100;
const int kMaxSignalGroupDescriptionChars = 1000;

/// Longest group message text kept (the signal itself may be up to 2 MB).
const int kMaxGroupMessageChars = 64 * 1024;

/// Longest group id / invitation id accepted. Ids are generated by the app
/// and short; a huge one is only a way to bloat storage.
const int kMaxSignalIdChars = 256;

/// [ZenSignal.content] of a `group_invite_ack` that says the invitation was
/// accepted, not only that it arrived.
const String kGroupJoinedAck = 'joined';

/// Largest number (either sign) read from a peer: every integer up to it
/// is exact as a JSON number on any platform, and sums of a few such
/// times or sizes stay far from overflowing.
const int kMaxSignalNumber = 9007199254740991;

/// Deepest nesting of maps and lists kept from a peer's payload (the
/// deepest real one, a call's description with its key block, is three).
const int _maxSignalDepth = 16;

/// The key of `msg_react` and `msg_delete` in a group that names the
/// author of the message they mean: members choose message ids themselves,
/// so one id can belong to messages of two members.
const String kChangeAuthorKey = 'author';

/// A ring that ended unanswered, told by the caller afterwards: `{callId,
/// kind, at}` (when the call was made, by the caller's clock). Sent
/// reliably, so a callee who was away when it rang still learns of it from
/// the caller's queue or a mailbox. A Zen before 1.16.5 does not know it
/// and ignores it; it never rings.
const String kCallMissedType = 'call_missed';

/// The mark in [ZenSignal.chatExtras] of a [kCallMissedType] notice, read as
/// the end of the call it names (`ZenSignalType.callEnd`): the call is over
/// wherever it is still on file, and anywhere else only the missed call is
/// noted ([isMissedCallNotice] in notification_privacy.dart).
const String kMissedCallMark = 'missed';

/// Set on the `call_end` a caller sends to the callee's other devices once
/// one device of theirs answered or declined (see `AccountRoutingTransport`),
/// and kept under the same key in [ZenSignal.chatExtras]: the ring there
/// stops without a word, as nothing was missed ([isCallTakenElsewhere]). A
/// Zen before 1.17.0 reads it as the caller's hang-up: it still stops
/// ringing (and notes a missed call, as it did).
const String kCallElsewhereKey = 'elsewhere';

/// Whether [signal] ends a call that another device of this account
/// answered or declined ([kCallElsewhereKey]).
bool isCallTakenElsewhere(ZenSignal signal) =>
    signal.type == ZenSignalType.callEnd &&
    signal.chatExtras?[kCallElsewhereKey] == true;

ZenSignal? zenSignalFromTransportPayload({
  required String sender,
  required Map<String, dynamic> payload,
}) =>
    // JSON from the wire can hold numbers no reader here can use (1e400 is
    // infinity, 1e300 has no exact integer) and nesting nothing here
    // needs. Read once into a copy without them, so no reader below (nor
    // the stores the signal ends up in) has to meet them.
    _signalFrom(sender, _finiteJsonMap(payload, 0));

ZenSignal? _signalFrom(String sender, Map<String, dynamic> payload) {
  final String type = _readString(payload['type']) ?? '';
  for (final String key in _idKeys) {
    final Object? id = payload[key];
    if (id is String && id.length > kMaxSignalIdChars) {
      // Ids are generated by the app and short; a huge one is only a way to
      // bloat storage (a group id ends up in the snapshot, the inbox, ...).
      return null;
    }
  }
  switch (type) {
    case 'friend_request':
      return ZenSignal(
        type: ZenSignalType.friendRequest,
        sender: sender,
        displayName: _readName(payload['senderName']),
        // The token of the invitation code it came from, if any.
        inviteId: switch (payload['it']) {
          final String token when PeerShareCodec.isInviteToken(token) => token,
          _ => null,
        },
        content: _readClipped(
          payload['message'],
          kMaxFriendRequestMessageChars,
        ),
      );
    case 'friend_accept':
      return ZenSignal(
        type: ZenSignalType.friendAccept,
        sender: sender,
        displayName: _readName(payload['senderName']),
      );
    case 'friend_reject':
      return ZenSignal(type: ZenSignalType.friendReject, sender: sender);
    case 'friend_cancel':
      return ZenSignal(type: ZenSignalType.friendCancel, sender: sender);
    case 'friend_remove':
      return ZenSignal(type: ZenSignalType.friendRemove, sender: sender);
    case 'message_ack':
      return ZenSignal(
        type: ZenSignalType.ack,
        sender: sender,
        messageId: _readString(payload['msgId']),
        content: 'message',
      );
    case 'message_read':
      return ZenSignal(
        type: ZenSignalType.messageRead,
        sender: sender,
        messageId: _readString(payload['msgId']),
      );
    case 'typing':
      return ZenSignal(
        type: ZenSignalType.typing,
        sender: sender,
        isTyping: _readBool(payload['isTyping']) ?? true,
      );
    case 'message_placeholder':
      return ZenSignal(
        type: ZenSignalType.message,
        sender: sender,
        messageId: _readString(payload['msgId']),
        displayName: _readName(payload['senderName']),
        content: _readString(payload['text']) ?? t('📎 Załącznik'),
        messageType: _readMessageType(payload['messageType']),
        fileName: safeFileName(_readString(payload['fileName'])),
        mimeType: _readString(payload['mimeType']),
        attachmentSizeBytes: _readInt(payload['attachmentSizeBytes']),
        durationMs: _readInt(payload['durationMs']),
        attachmentTransferBytes: _readInt(payload['attachmentTransferBytes']),
        chunkCount: _readInt(payload['chunkCount']),
        chunkIndex: _readInt(payload['chunkIndex']),
        isPlaceholder: true,
      );
    case 'message_chunk':
      return ZenSignal(
        type: ZenSignalType.messageChunk,
        sender: sender,
        messageId: _readString(payload['msgId']),
        displayName: _readName(payload['senderName']),
        content: _readString(payload['text']) ?? t('📎 Załącznik'),
        messageType: _readMessageType(payload['messageType']),
        fileName: safeFileName(_readString(payload['fileName'])),
        mimeType: _readString(payload['mimeType']),
        attachmentSizeBytes: _readInt(payload['attachmentSizeBytes']),
        durationMs: _readInt(payload['durationMs']),
        attachmentTransferBytes: _readInt(payload['attachmentTransferBytes']),
        chunkIndex: _readInt(payload['chunkIndex']),
        chunkCount: _readInt(payload['chunkCount']),
        chunkData: _readString(payload['chunkData']),
      );
    case 'message_chunk_ack':
      return ZenSignal(
        type: ZenSignalType.messageChunkAck,
        sender: sender,
        messageId: _readString(payload['msgId']),
        chunkIndex: _readInt(payload['chunkIndex']),
      );
    case 'message':
      final String? text = _readString(payload['text']);
      final String? attachmentData = _readString(payload['attachmentData']);
      if ((text == null || text.isEmpty) &&
          (attachmentData == null || attachmentData.isEmpty)) {
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.message,
        sender: sender,
        messageId: _readString(payload['msgId']),
        displayName: _readName(payload['senderName']),
        content: text ?? t('📎 Załącznik'),
        messageType: _readMessageType(payload['messageType']),
        attachmentData: attachmentData,
        attachmentEncoding: _readString(payload['attachmentEncoding']),
        fileName: safeFileName(_readString(payload['fileName'])),
        mimeType: _readString(payload['mimeType']),
        attachmentSizeBytes: _readInt(payload['attachmentSizeBytes']),
        durationMs: _readInt(payload['durationMs']),
        sentAtMillis: _readTimestamp(payload['createdAt']),
        disappearSeconds: _readInt(payload['ttl']),
        // When that timer was set (absent before 1.17.0).
        disappearSetAt: _readInt(payload['ttlAt']),
        miniProfile: _readMiniProfile(payload['mp']),
        chatExtras: _readChatExtras(payload),
      );
    case 'message_transfer_cancel':
      return ZenSignal(
        type: ZenSignalType.transferCancel,
        sender: sender,
        messageId: _readString(payload['msgId']),
      );
    case 'transfer_offer':
      return ZenSignal(
        type: ZenSignalType.transferOffer,
        sender: sender,
        messageId: _readString(payload['transferId']),
        content: _readString(payload['text']) ?? t('📎 Załącznik'),
        messageType: _readMessageType(payload['messageType']),
        fileName: safeFileName(_readString(payload['fileName'])),
        mimeType: _readString(payload['mimeType']),
        attachmentSizeBytes: _readInt(payload['attachmentSizeBytes']),
        durationMs: _readInt(payload['durationMs']),
        attachmentTransferBytes: _readInt(payload['fileSize']),
        sessionDescription: _readMap(payload['description']),
      );
    case 'transfer_answer':
      return ZenSignal(
        type: ZenSignalType.transferAnswer,
        sender: sender,
        messageId: _readString(payload['transferId']),
        sessionDescription: _readMap(payload['description']),
      );
    case 'call_invite':
      return ZenSignal(
        type: ZenSignalType.callInvite,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'offer':
      return ZenSignal(
        type: ZenSignalType.callOffer,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
        sessionDescription: _readMap(payload['description']),
      );
    case 'answer':
      return ZenSignal(
        type: ZenSignalType.callAnswer,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
        sessionDescription: _readMap(payload['description']),
      );
    case 'ringing':
      return ZenSignal(
        type: ZenSignalType.callRinging,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'call_accept':
      return ZenSignal(
        type: ZenSignalType.callAccept,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'call_decline':
      // Teardown signals name the call they end (see `busy`, `hangup`).
      if (_readString(payload['callId']) == null) {
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.callDecline,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'call_offer_request':
      return ZenSignal(
        type: ZenSignalType.callOfferRequest,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'busy':
      if (_readString(payload['callId']) == null) {
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.callBusy,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
      );
    case 'hangup':
    case 'call_end':
      if (_readString(payload['callId']) == null) {
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.callEnd,
        sender: sender,
        callId: _readString(payload['callId']),
        content: _readString(payload['kind']) ?? 'audio',
        chatExtras: payload[kCallElsewhereKey] == true
            ? const <String, dynamic>{kCallElsewhereKey: true}
            : null,
      );
    case 'call_missed': // kCallMissedType
      // Names the one call it is about, like the teardown signals.
      final String? missedCallId = _readString(payload['callId']);
      if (missedCallId == null) {
        return null;
      }
      final int? calledAt = _readInt(payload['at']);
      return ZenSignal(
        type: ZenSignalType.callEnd,
        sender: sender,
        callId: missedCallId,
        content: _readString(payload['kind']) == 'video' ? 'video' : 'audio',
        sentAtMillis: calledAt != null && calledAt > 0 ? calledAt : null,
        chatExtras: const <String, dynamic>{kMissedCallMark: true},
      );
    case 'group_invite':
      if (_readString(payload['groupId']) == null) {
        // Every group signal is keyed by its group; without one it cannot
        // be matched to anything and would only produce a phantom group.
        return null;
      }
      final Object? rawMembersValue = payload['memberAddresses'];
      final List<dynamic>? rawMembers = rawMembersValue is List<dynamic>
          ? rawMembersValue
          : null;
      final List<String>? memberAddresses = rawMembers
          ?.whereType<String>()
          .map((String e) => e.trim())
          .where((String e) => e.isNotEmpty && e.length <= kMaxSignalIdChars)
          // A real group is far smaller (every message goes to each member);
          // an endless list would only grow the group and the snapshot.
          .take(kMaxGroupMemberCount)
          .toList();
      return ZenSignal(
        type: ZenSignalType.groupInvite,
        sender: sender,
        groupId: _readString(payload['groupId']),
        groupName: _readClipped(payload['groupName'], kMaxSignalGroupNameChars),
        content: _readClipped(
          payload['description'],
          kMaxSignalGroupDescriptionChars,
        ),
        memberAddresses: memberAddresses,
        memberNames: switch (payload['memberNames']) {
          final List<dynamic> names => <String>[
            for (final Object? name in names.take(kMaxGroupMemberCount))
              _readName(name) ?? '',
          ],
          _ => null,
        },
        avatarPreset: _readString(payload['avatarPreset']),
        displayName: _readName(payload['senderName']),
        inviteId: _readString(payload['inviteId']),
        // A member-list update that names the one person it adds, stamped
        // with the adder's clock; the members' list for someone who just
        // joined also tells who left and when (see
        // [kGroupAddedKey], [kGroupLeftKey]).
        sentAtMillis: _readInt(payload['at']),
        chatExtras: _readGroupMembershipExtras(payload),
      );
    case 'group_invite_ack':
      if (_readString(payload['groupId']) == null) {
        // Every group signal is keyed by its group; without one it cannot
        // be matched to anything and would only produce a phantom group.
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.groupInviteAck,
        sender: sender,
        groupId: _readString(payload['groupId']),
        content: payload['joined'] == true ? kGroupJoinedAck : null,
      );
    case 'group_message':
      if (_readString(payload['groupId']) == null) {
        // Every group signal is keyed by its group; without one it cannot
        // be matched to anything and would only produce a phantom group.
        return null;
      }
      final ChatMessageType groupType = _readMessageType(
        payload['messageType'],
      );
      return ZenSignal(
        type: ZenSignalType.groupMessage,
        sender: sender,
        groupId: _readString(payload['groupId']),
        groupName: _readClipped(payload['groupName'], kMaxSignalGroupNameChars),
        messageId: _readString(payload['msgId']),
        content:
            _readClipped(payload['text'], kMaxGroupMessageChars) ??
            (groupType == ChatMessageType.text
                ? null
                : chatMessageLabelForType(
                    groupType,
                    fileName: safeFileName(_readString(payload['fileName'])),
                    mimeType: _readString(payload['mimeType']),
                  )),
        displayName: _readName(payload['senderName']),
        sentAtMillis: _readTimestamp(payload['timestamp']),
        disappearSeconds: _readInt(payload['ttl']),
        disappearSetAt: _readInt(payload['ttlAt']),
        // A file in a group: inline, or as blocks to fetch (`media`).
        messageType: groupType == ChatMessageType.text ? null : groupType,
        attachmentData: _readString(payload['attachmentData']),
        attachmentEncoding: _readString(payload['attachmentEncoding']),
        fileName: safeFileName(_readString(payload['fileName'])),
        mimeType: _readString(payload['mimeType']),
        attachmentSizeBytes: _readInt(payload['attachmentSizeBytes']),
        durationMs: _readInt(payload['durationMs']),
        chatExtras: _readChatExtras(payload),
      );
    case 'msg_react':
    case 'msg_edit':
    case 'msg_delete':
      final String? targetId = _readString(payload['msgId']);
      if (targetId == null) {
        return null;
      }
      final String? emoji = _readString(payload['emoji']);
      final String? author = type == 'msg_edit'
          ? null
          : _readAuthor(payload[kChangeAuthorKey]);
      return ZenSignal(
        type: switch (type) {
          'msg_react' => ZenSignalType.messageReaction,
          'msg_edit' => ZenSignalType.messageEdit,
          _ => ZenSignalType.messageDelete,
        },
        sender: sender,
        messageId: targetId,
        groupId: _readString(payload['groupId']),
        content: type == 'msg_edit'
            ? _readClipped(payload['text'], kMaxGroupMessageChars)
            : null,
        sentAtMillis: _readInt(payload['at']),
        chatExtras: switch (type) {
          'msg_react' => <String, dynamic>{
            // Empty: the reaction is taken back.
            'emoji': emoji != null && emoji.length <= kMaxReactionChars
                ? emoji
                : '',
            kChangeAuthorKey: ?author,
          },
          // A newer position of a shared one, or a poll its author ended.
          'msg_edit' => _editExtras(payload),
          _ =>
            author == null ? null : <String, dynamic>{kChangeAuthorKey: author},
        },
      );
    case 'disappear_timer':
      return ZenSignal(
        type: ZenSignalType.disappearTimer,
        sender: sender,
        groupId: _readString(payload['groupId']),
        disappearSeconds: _readInt(payload['seconds']) ?? 0,
        sentAtMillis: _readInt(payload['at']),
      );
    case 'group_leave':
      if (_readString(payload['groupId']) == null) {
        return null;
      }
      return ZenSignal(
        type: ZenSignalType.groupLeave,
        sender: sender,
        groupId: _readString(payload['groupId']),
        // When the leaver left, by its own clock (absent before 1.16.5).
        sentAtMillis: _readInt(payload['at']),
      );
    case 'profile_update':
      return ZenSignal(
        type: ZenSignalType.profileUpdate,
        sender: sender,
        displayName: _readString(payload['name']),
        content: _readString(payload['status']),
        bio: _readString(payload['bio']),
        attachmentData: _readString(payload['avatar']),
        sentAtMillis: _readInt(payload['v']),
      );
    case 'group_call_invite':
    case 'group_call_join':
    case 'group_call_state':
    case 'group_call_leave':
    case 'group_call_decline':
    case 'gc_offer':
    case 'gc_answer':
      final String? callGroupId = _readString(payload['groupId']);
      final String? groupCallId = _readString(payload['callId']);
      if (callGroupId == null || groupCallId == null) {
        // A group call is addressed by both; without them a ring could not be
        // matched to its call (every re-ring used to look like a new call).
        return null;
      }
      return ZenSignal(
        type: switch (type) {
          'group_call_invite' => ZenSignalType.groupCallInvite,
          'group_call_join' => ZenSignalType.groupCallJoin,
          'group_call_state' => ZenSignalType.groupCallState,
          'group_call_leave' => ZenSignalType.groupCallLeave,
          'group_call_decline' => ZenSignalType.groupCallDecline,
          'gc_offer' => ZenSignalType.groupCallOffer,
          _ => ZenSignalType.groupCallAnswer,
        },
        sender: sender,
        groupId: callGroupId,
        callId: groupCallId,
        groupName: _readClipped(payload['groupName'], kMaxSignalGroupNameChars),
        content: _readString(payload['kind']) ?? 'audio',
        memberAddresses: _readStringList(payload['participants']),
        sessionDescription: _readMap(payload['description']),
        displayName: _readName(payload['senderName']),
        cameraOn: _readBool(payload['camera']),
      );
    default:
      return null;
  }
}

/// What a `group_invite` carries about single members, kept in
/// [ZenSignal.chatExtras] under the same keys: the one address a
/// member-list update adds ([kGroupAddedKey]), who left the group and
/// when ([kGroupLeftKey]), and who was added by name and when
/// ([kGroupAddsKey]); each an address-to-time map of at most
/// [kMaxGroupMemberCount] entries. `null` when it carries none (a Zen
/// before 1.16.5 sends none).
Map<String, dynamic>? _readGroupMembershipExtras(Map<String, dynamic> payload) {
  final String? added = _readString(payload[kGroupAddedKey]);
  final Map<String, int> departures = _readGroupStamps(payload[kGroupLeftKey]);
  final Map<String, int> adds = _readGroupStamps(payload[kGroupAddsKey]);
  final Map<String, dynamic> out = <String, dynamic>{
    if (added != null && added.length <= kMaxSignalIdChars)
      kGroupAddedKey: PeerShareCodec.normalizeAddress(added),
    if (departures.isNotEmpty) kGroupLeftKey: departures,
    if (adds.isNotEmpty) kGroupAddsKey: adds,
  };
  return out.isEmpty ? null : out;
}

/// An address-to-time map of a `group_invite` ([kGroupLeftKey],
/// [kGroupAddsKey]): at most [kMaxGroupMemberCount] entries, each a usable
/// address with a positive time.
Map<String, int> _readGroupStamps(Object? raw) {
  final Map<String, int> stamps = <String, int>{};
  if (raw is! Map) {
    return stamps;
  }
  for (final MapEntry<dynamic, dynamic> e in raw.entries) {
    if (stamps.length >= kMaxGroupMemberCount) {
      break;
    }
    final String? address = _readString(e.key);
    final int? at = _readInt(e.value);
    if (address != null &&
        address.length <= kMaxSignalIdChars &&
        at != null &&
        at > 0) {
      stamps[PeerShareCodec.normalizeAddress(address)] = at;
    }
  }
  return stamps;
}

/// The reply (`re`), forwarding (`fwd`), content-addressed file (`media`)
/// mentions (`men`), a poll (`poll`) and a position (`loc`) a chat or group message carries; `null` when none.
/// What an edit carries beside its text: a newer position of a shared one
/// ([kLocationKey]) or the poll its author ended ([kPollKey]).
Map<String, dynamic>? _editExtras(Map<String, dynamic> payload) {
  final ChatLocation? location = ChatLocation.fromJson(payload[kLocationKey]);
  final ChatPoll? poll = ChatPoll.fromJson(payload[kPollKey]);
  final Map<String, dynamic> out = <String, dynamic>{
    if (location != null) kLocationKey: location.toJson(),
    if (poll != null && poll.closedAtMillis != null) kPollKey: poll.toJson(),
  };
  return out.isEmpty ? null : out;
}

Map<String, dynamic>? _readChatExtras(Map<String, dynamic> payload) {
  final ChatReply? reply = ChatReply.fromJson(payload['re']);
  // A group file's reference is kept until the file arrives: only its
  // known fields, never the peer's map as it came.
  final Map<String, dynamic>? media = chatMediaRefFromJson(payload['media']);
  final List<Mention> mentions = mentionsFromJson(payload[kMentionsKey]);
  final ChatPoll? poll = ChatPoll.fromJson(payload[kPollKey]);
  final ChatLocation? location = ChatLocation.fromJson(payload[kLocationKey]);
  final Map<String, dynamic> out = <String, dynamic>{
    if (reply != null) 're': reply.toJson(),
    if (payload['fwd'] == true) 'fwd': true,
    'media': ?media,
    if (mentions.isNotEmpty) kMentionsKey: mentionsToJson(mentions),
    if (poll != null) kPollKey: poll.toJson(),
    if (location != null) kLocationKey: location.toJson(),
  };
  return out.isEmpty ? null : out;
}

ChatMessageType _readMessageType(Object? value) {
  final String? raw = _readString(value);
  return switch (raw) {
    'image' => ChatMessageType.image,
    'file' => ChatMessageType.file,
    'voice' => ChatMessageType.voice,
    'video' => ChatMessageType.video,
    _ => ChatMessageType.text,
  };
}

/// A whole number from a peer: an integer, or a finite number, within
/// [kMaxSignalNumber] either way; anything else is absent (`toInt` throws
/// on infinity and NaN).
int? _readInt(Object? value) {
  return switch (value) {
    final num typed when _usable(typed) => typed.toInt(),
    _ => null,
  };
}

/// Whether [n] is finite and within [kMaxSignalNumber] either way (a
/// range check, not `abs`: the smallest integer is its own `abs`).
bool _usable(num n) =>
    n.isFinite && n >= -kMaxSignalNumber && n <= kMaxSignalNumber;

/// [value] (a decoded JSON value) without what no reader can use: numbers
/// that are not finite or lie beyond [kMaxSignalNumber], and anything
/// nested deeper than [_maxSignalDepth]. In a map such an entry is
/// dropped (absent, as if not sent); in a list it becomes `null`, so the
/// other items keep their places (a poll's answers are counted by place).
Object? _finiteJson(Object? value, int depth) {
  return switch (value) {
    final num n when !_usable(n) => null,
    final Map<dynamic, dynamic> map =>
      depth >= _maxSignalDepth ? null : _finiteJsonMap(map, depth + 1),
    final List<dynamic> list =>
      depth >= _maxSignalDepth
          ? null
          : <dynamic>[
              for (final Object? item in list) _finiteJson(item, depth + 1),
            ],
    _ => value,
  };
}

Map<String, dynamic> _finiteJsonMap(Map<dynamic, dynamic> map, int depth) {
  final Map<String, dynamic> out = <String, dynamic>{};
  for (final MapEntry<dynamic, dynamic> entry in map.entries) {
    final Object? value = _finiteJson(entry.value, depth);
    if (value != null || entry.value == null) {
      out[entry.key.toString()] = value;
    }
  }
  return out;
}

/// The mini-profile (`mp`) a message to someone who is not a friend
/// carries: its name and its photo's reference, nothing else. A map with
/// nothing usable stays an empty map (it still marks such a message).
Map<String, dynamic>? _readMiniProfile(Object? value) {
  if (value is! Map) {
    return null;
  }
  final String? name = _readName(value['n']);
  final Map<String, dynamic>? avatar = chatMediaRefFromJson(value['av']);
  return <String, dynamic>{'n': ?name, 'av': ?avatar};
}

/// The address a `msg_react` / `msg_delete` names as the author of its
/// message ([kChangeAuthorKey]); `null` when it names none (a Zen before
/// it sent no author).
String? _readAuthor(Object? value) {
  final String? author = _readString(value);
  if (author == null || author.toLowerCase() == 'self') {
    return null;
  }
  return PeerShareCodec.normalizeAddress(author);
}

Map<String, dynamic>? _readMap(Object? value) {
  if (value is! Map<dynamic, dynamic>) {
    return null;
  }
  return value.map<String, dynamic>((dynamic key, dynamic entry) {
    return MapEntry<String, dynamic>(key.toString(), entry);
  });
}

String? _readString(Object? value) {
  if (value is! String) {
    return null;
  }
  final String trimmed = value.trim();
  return trimmed.isEmpty ? null : trimmed;
}

/// Keys whose values are ids (see [kMaxSignalIdChars]).
const List<String> _idKeys = <String>[
  'groupId',
  'inviteId',
  'callId',
  'msgId',
  'transferId',
  kChangeAuthorKey,
];

/// [_readString], cut to at most [maxChars] UTF-16 units without splitting a
/// surrogate pair.
String? _readClipped(Object? value, int maxChars) {
  final String? text = _readString(value);
  if (text == null || text.length <= maxChars) {
    return text;
  }
  int end = maxChars;
  final int last = text.codeUnitAt(end - 1);
  if (last >= 0xD800 && last <= 0xDBFF) {
    end -= 1;
  }
  final String clipped = text.substring(0, end).trimRight();
  return clipped.isEmpty ? null : clipped;
}

/// A name a peer gave itself. Names only label someone; the clip keeps one
/// from flooding a notification or the stored state. (A group member can
/// still pick any name, including one that looks like someone else's - the
/// app's own name for a friend always wins where it has one.)
String? _readName(Object? value) {
  return _readClipped(value, kMaxSignalSenderNameChars);
}

List<String>? _readStringList(Object? value) {
  if (value is! List<dynamic>) {
    return null;
  }
  return value
      .whereType<String>()
      .map((String e) => e.trim())
      .where((String e) => e.isNotEmpty)
      .take(64)
      .toList(growable: false);
}

bool? _readBool(Object? value) {
  if (value is bool) {
    return value;
  }
  if (value is String) {
    if (value.toLowerCase() == 'true') {
      return true;
    }
    if (value.toLowerCase() == 'false') {
      return false;
    }
  }
  return null;
}

/// Epoch millis from an ISO-8601 string or a number; `null` otherwise.
int? _readTimestamp(Object? value) {
  if (value is num) {
    return _readInt(value);
  }
  if (value is String) {
    return _readInt(DateTime.tryParse(value)?.millisecondsSinceEpoch);
  }
  return null;
}
