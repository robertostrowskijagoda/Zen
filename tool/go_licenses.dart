// Regenerates the licenses of the Go modules compiled into the network
// bridge (native/yggdrasil_bridge) from the local Go module cache:
//
//   dart run tool/go_licenses.dart
//
// Writes assets/licenses/go/ (index.txt and one text per module, shown in
// "O aplikacji → Licencje") and native/yggdrasil_bridge/LICENSES-GO.txt
// (attached to releases). Run it after changing go.mod. It needs Go (for
// `go env GOMODCACHE GOROOT`) and the modules downloaded, which any build of
// the bridge does. See docs/RELEASES.md.
import 'dart:io';

const String _bridgeDir = 'native/yggdrasil_bridge';
const String _assetDir = 'assets/licenses/go';
const String _combinedPath = '$_bridgeDir/LICENSES-GO.txt';
const String _goStdlib = 'Go standard library';

/// License files below the module root, in packages the bridge links (the
/// root's LICENSE / COPYRIGHT files are always taken).
const Map<String, List<String>> _nestedLicenses = <String, List<String>>{
  'github.com/klauspost/compress': <String>[
    'zstd/internal/xxhash/LICENSE.txt',
    'internal/snapref/LICENSE',
  ],
};

final RegExp _licenseFileName = RegExp(
  r'^(licen[cs]e|copying|copyright|notice)',
  caseSensitive: false,
);

final class _Module {
  const _Module({
    required this.path,
    required this.version,
    required this.directory,
    required this.assetName,
    required this.source,
  });

  final String path;
  final String version;
  final String directory;
  final String assetName;
  final String source;
}

Future<void> main() async {
  final String goMod = File('$_bridgeDir/go.mod').readAsStringSync();
  final String modCache = await _goEnv('GOMODCACHE');
  final String goRoot = await _goEnv('GOROOT');
  final List<_Module> modules = <_Module>[
    _Module(
      path: _goStdlib,
      version: _goDirective(goMod),
      directory: goRoot,
      assetName: 'go.txt',
      source: 'https://go.googlesource.com/go',
    ),
    for (final (String, String) req in _requirements(goMod))
      _Module(
        path: req.$1,
        version: req.$2,
        directory: '$modCache/${_escapeModulePath(req.$1)}@${req.$2}',
        assetName: '${req.$1.replaceAll('/', '_')}.txt',
        source: _sourceUrl(req.$1),
      ),
  ];

  final Directory assets = Directory(_assetDir)..createSync(recursive: true);
  final List<String> index = <String>[
    '# Generated by tool/go_licenses.dart from the Go module cache. Do not edit.',
    '# module<TAB>version<TAB>file<TAB>source',
  ];
  final List<String> combined = <String>[
    'Licencje modułów Go wkompilowanych w most sieci Zen',
    '(native/yggdrasil_bridge: libyggdrasil_bridge.so, yggdrasil_bridge.dll,',
    'libyggdrasil_bridge.a). Wygenerowane przez tool/go_licenses.dart.',
    '',
  ];
  final String rule = '=' * 72;
  for (final _Module module in modules) {
    final String? text = _licenseText(module);
    if (text == null) {
      stderr.writeln(
        'Brak licencji dla ${module.path} ${module.version} w '
        '${module.directory}. Zbuduj most (go mod download) i spróbuj '
        'jeszcze raz.',
      );
      exitCode = 1;
      return;
    }
    File(
      '${assets.path}/${module.assetName}',
    ).writeAsStringSync(text, flush: true);
    index.add(
      <String>[
        module.path,
        module.version,
        module.assetName,
        module.source,
      ].join('\t'),
    );
    combined.addAll(<String>[
      rule,
      '${module.path} ${module.version}',
      'Kod źródłowy: ${module.source}',
      rule,
      '',
      text,
    ]);
  }

  // Drop texts of modules that are no longer in go.mod.
  final Set<String> keep = <String>{
    'index.txt',
    for (final _Module module in modules) module.assetName,
  };
  for (final FileSystemEntity entity in assets.listSync()) {
    final String name = entity.uri.pathSegments.last;
    if (entity is File && !keep.contains(name)) {
      entity.deleteSync();
    }
  }
  File(
    '${assets.path}/index.txt',
  ).writeAsStringSync('${index.join('\n')}\n', flush: true);
  File(_combinedPath).writeAsStringSync(combined.join('\n'), flush: true);
  stdout.writeln(
    'Licencje Go: ${modules.length} modułów w $_assetDir i $_combinedPath.',
  );
}

Future<String> _goEnv(String name) async {
  final String? fromEnvironment = Platform.environment[name];
  if (fromEnvironment != null && fromEnvironment.isNotEmpty) {
    return fromEnvironment;
  }
  final ProcessResult result = await Process.run('go', <String>[
    'env',
    name,
  ], workingDirectory: _bridgeDir);
  if (result.exitCode != 0) {
    throw StateError('go env $name: ${result.stderr}');
  }
  return (result.stdout as String).trim();
}

/// `go 1.26.0` → `1.26`.
String _goDirective(String goMod) {
  final RegExpMatch? match = RegExp(
    r'^go\s+(\d+)\.(\d+)',
    multiLine: true,
  ).firstMatch(goMod);
  if (match == null) {
    throw const FormatException('go.mod has no go directive');
  }
  return '${match.group(1)}.${match.group(2)}';
}

/// Module path and version of every `require` (direct and indirect), in
/// go.mod order.
List<(String, String)> _requirements(String goMod) {
  final List<(String, String)> out = <(String, String)>[];
  bool inBlock = false;
  for (final String raw in goMod.split('\n')) {
    String line = raw.trim();
    final int comment = line.indexOf('//');
    if (comment >= 0) {
      line = line.substring(0, comment).trim();
    }
    if (line.isEmpty) {
      continue;
    }
    if (line == 'require (') {
      inBlock = true;
      continue;
    }
    if (inBlock && line == ')') {
      inBlock = false;
      continue;
    }
    if (!inBlock) {
      if (!line.startsWith('require ')) {
        continue;
      }
      line = line.substring('require '.length).trim();
    }
    final List<String> parts = line.split(RegExp(r'\s+'));
    if (parts.length >= 2) {
      out.add((parts[0], parts[1]));
    }
  }
  return out;
}

/// The module cache spells capital letters as `!` + lower case.
String _escapeModulePath(String path) {
  final StringBuffer out = StringBuffer();
  for (final int unit in path.codeUnits) {
    if (unit >= 0x41 && unit <= 0x5A) {
      out
        ..write('!')
        ..writeCharCode(unit + 0x20);
    } else {
      out.writeCharCode(unit);
    }
  }
  return out.toString();
}

String _sourceUrl(String modulePath) {
  const String xPrefix = 'golang.org/x/';
  if (modulePath.startsWith(xPrefix)) {
    return 'https://go.googlesource.com/${modulePath.substring(xPrefix.length)}';
  }
  return 'https://${modulePath.replaceFirst(RegExp(r'/v\d+$'), '')}';
}

/// The module's license files joined into one text, or `null` when there
/// are none.
String? _licenseText(_Module module) {
  final Directory directory = Directory(module.directory);
  if (!directory.existsSync()) {
    return null;
  }
  final List<(String, File)> files = <(String, File)>[];
  final List<File> rootFiles =
      directory
          .listSync()
          .whereType<File>()
          .where((File f) => _licenseFileName.hasMatch(f.uri.pathSegments.last))
          .toList()
        ..sort(
          (File a, File b) => a.uri.pathSegments.last.toLowerCase().compareTo(
            b.uri.pathSegments.last.toLowerCase(),
          ),
        );
  for (final File file in rootFiles) {
    files.add((file.uri.pathSegments.last, file));
  }
  for (final String nested
      in _nestedLicenses[module.path] ?? const <String>[]) {
    files.add((nested, File('${directory.path}/$nested')));
  }
  if (files.isEmpty) {
    return null;
  }
  final StringBuffer out = StringBuffer();
  for (int i = 0; i < files.length; i++) {
    final (String name, File file) = files[i];
    final String text = file
        .readAsStringSync()
        .replaceAll('\r\n', '\n')
        .trimRight();
    if (i > 0) {
      out.write('\n\n($name)\n\n');
    }
    out.write(text);
  }
  out.write('\n');
  return out.toString();
}
